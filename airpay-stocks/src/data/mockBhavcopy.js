// Helper: get bhavcopy data for a symbol
export function getBhavcopyBySymbol(symbol) {
  const stock = stockBhavcopy.find(s => s.SYMBOL === symbol);
  if (stock) return { ...stock, type: "EQ" };
  const etf = etfBhavcopy.find(e => e.SYMBOL === symbol);
  if (etf) return { ...etf, type: "MF", CLOSE_PRICE: etf["CLOSE PRICE"], PREV_CL_PR: etf["PREVIOUS CLOSE PRICE"], OPEN_PRICE: etf["OPEN PRICE"], HIGH_PRICE: etf["HIGH PRICE"], LOW_PRICE: etf["LOW PRICE"], NET_TRDVAL: etf["NET TRADED VALUE"], NET_TRDQTY: etf["NET TRADED QTY"], HI_52_WK: etf["52 WEEK HIGH"], LO_52_WK: etf["52 WEEK LOW"] };
  return null;
}

// Helper: get all bhavcopy entries (normalized)
export function getAllBhavcopy() {
  const stocks = stockBhavcopy.map(s => ({ ...s, type: "EQ" }));
  const etfs = etfBhavcopy.map(e => ({
    type: "MF",
    SERIES: e.SERIES,
    SYMBOL: e.SYMBOL,
    SECURITY: e.SECURITY,
    PREV_CL_PR: e["PREVIOUS CLOSE PRICE"],
    OPEN_PRICE: e["OPEN PRICE"],
    HIGH_PRICE: e["HIGH PRICE"],
    LOW_PRICE: e["LOW PRICE"],
    CLOSE_PRICE: e["CLOSE PRICE"],
    NET_TRDVAL: e["NET TRADED VALUE"],
    NET_TRDQTY: e["NET TRADED QTY"],
    TRADES: e.TRADES,
    HI_52_WK: e["52 WEEK HIGH"],
    LO_52_WK: e["52 WEEK LOW"],
    UNDERLYING: e.UNDERLYING,
  }));
  return [...stocks, ...etfs];
}
